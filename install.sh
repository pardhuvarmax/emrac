#!/bin/sh
# emrac installer for Arch Linux and Arch-based distributions.
#
#   curl -fsSL https://pardhuvarmax.github.io/emrac/install.sh | sh
#   curl -fsSL https://pardhuvarmax.github.io/emrac/install.sh | sh -s -- --yes
#
# Reading it first is better than piping it: download it, read it, then run it
# (`curl -fsSLO <url>`, `less install.sh`, `sh install.sh`).
#
# What it does, in order:
#   1. downloads the release tarball and checks its SHA-256 against the value
#      pinned below (it stops if they differ);
#   2. builds a pacman package from it with makepkg, in a temporary folder;
#   3. installs that package with `sudo pacman -U`, so pacman tracks every file
#      and `sudo pacman -Rns emrac` removes it.
#
# It never runs as root (makepkg refuses to), only asks for sudo where pacman
# needs it, installs nothing outside the package, and removes its temporary
# folder. The program is GPL-3.0-or-later; see LICENSE in the tarball.
#
# The two values below are updated by dev/pin-install-script.sh when a release
# is tagged; the recipe further down is the same as the AUR package's.

set -eu

TAG="r3"
VERSION="0.3.0"
SHA256="ccc0d9027a0eb5f3a96ecbcc1f0be33dea50f3200a19aa7517dc779111324eb8"
URL="https://github.com/pardhuvarmax/emrac/archive/refs/tags/${TAG}.tar.gz"

ASSUME_YES=0
DRY_RUN=0
UNINSTALL=0

say() { printf '%s\n' "$*"; }
note() { printf 'emrac installer: %s\n' "$*"; }
die() {
    printf 'emrac installer: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<'EOF'
Usage: install.sh [options]

Builds emrac from its release tarball and installs it with pacman.

  -y, --yes        do not ask questions (build and install without prompting;
                   sudo may still ask for your password)
  -n, --dry-run    show what would happen and stop
      --uninstall  remove the emrac package (sudo pacman -Rns emrac)
  -h, --help       show this help
EOF
}

# Is there a terminal to ask on? (When the script is piped into sh, standard
# input is the script itself, so questions go to /dev/tty.)
have_tty() { (: </dev/tty) 2>/dev/null; }

ask() {
    [ "$ASSUME_YES" = 1 ] && return 0
    have_tty || die "there is no terminal to ask on; run it from a terminal, or pass --yes"
    printf '%s [y/N] ' "$1" >/dev/tty
    read -r answer </dev/tty || return 1
    case $answer in
    y | Y | yes | YES | Yes) return 0 ;;
    *) return 1 ;;
    esac
}

need() {
    command -v "$1" >/dev/null 2>&1 || missing="$missing $1"
}

check_system() {
    [ "$(id -u)" -ne 0 ] || die "run this as your normal user, not root: makepkg refuses to build as root, and sudo is used only where pacman needs it"

    os_id=""
    os_like=""
    if [ -r /etc/os-release ]; then
        os_id=$(sed -n 's/^ID=//p' /etc/os-release | tr -d '"' | head -n 1)
        os_like=$(sed -n 's/^ID_LIKE=//p' /etc/os-release | tr -d '"' | head -n 1)
    fi
    case " $os_id $os_like " in
    *" arch "*) ;;
    *) die "this installer is for Arch Linux and Arch-based systems (found: ${os_id:-unknown}); on other systems build from source, see the README" ;;
    esac

    missing=""
    for tool in pacman makepkg sudo curl sha256sum tar sed; do need "$tool"; done
    [ -z "$missing" ] || die "missing tools:$missing; install them with: sudo pacman -S --needed base-devel sudo curl"
    command -v cc >/dev/null 2>&1 || command -v gcc >/dev/null 2>&1 ||
        die "no C compiler found (cargo needs one to link); install the base-devel group: sudo pacman -S --needed base-devel"
}

show_plan() {
    cat <<EOF

emrac $VERSION ($TAG) will be installed like this:

  1. download $URL
     and check its SHA-256 against
     $SHA256
  2. build the package with makepkg in a temporary folder
     (build dependencies cargo and clang, and the runtime dependencies pacman,
      git, sudo, libarchive, fakeroot and bubblewrap, are installed through
      pacman if missing, using sudo)
  3. install the package with: sudo pacman -U

It installs /usr/bin/emrac, shell completions, the license and the README, and
nothing else. Remove it later with: sudo pacman -Rns emrac

EOF
}

write_pkgbuild() {
    cat >PKGBUILD <<'EOF'
# Generated by emrac's install.sh; the same recipe as the AUR package.
pkgname=emrac
pkgver=@VERSION@
pkgrel=1
_tag=@TAG@
pkgdesc='A hybrid package management platform for Arch Linux'
arch=('x86_64')
url='https://github.com/pardhuvarmax/emrac'
license=('GPL-3.0-or-later')
depends=('pacman' 'git' 'sudo' 'libarchive' 'fakeroot' 'bubblewrap')
makedepends=('cargo' 'clang')
options=('!lto' '!debug')
optdepends=('systemd: memory and process limits for sandboxed AUR builds')
source=("$pkgname-$_tag.tar.gz::$url/archive/refs/tags/$_tag.tar.gz")
sha256sums=('@SHA256@')

prepare() {
  cd "$pkgname-$_tag"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch --locked --target "$(rustc -vV | sed -n 's/host: //p')"
}

build() {
  cd "$pkgname-$_tag"
  export RUSTUP_TOOLCHAIN=stable
  export CARGO_TARGET_DIR=target
  # keep the builder's paths out of the binary
  export RUSTFLAGS="$RUSTFLAGS --remap-path-prefix=$HOME=~ --remap-path-prefix=$srcdir=."
  cargo build --frozen --release
}

check() {
  cd "$pkgname-$_tag"
  export RUSTUP_TOOLCHAIN=stable
  cargo test --frozen
}

package() {
  cd "$pkgname-$_tag"
  install -Dm755 target/release/emrac "$pkgdir/usr/bin/emrac"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
  target/release/emrac completion bash | install -Dm644 /dev/stdin "$pkgdir/usr/share/bash-completion/completions/emrac"
  target/release/emrac completion zsh  | install -Dm644 /dev/stdin "$pkgdir/usr/share/zsh/site-functions/_emrac"
  target/release/emrac completion fish | install -Dm644 /dev/stdin "$pkgdir/usr/share/fish/vendor_completions.d/emrac.fish"
}
EOF
    sed -i -e "s|@VERSION@|$VERSION|" -e "s|@TAG@|$TAG|" -e "s|@SHA256@|$SHA256|" PKGBUILD
}

install_emrac() {
    if installed=$(pacman -Q emrac 2>/dev/null); then
        case $installed in
        "emrac $VERSION-"*)
            note "$installed is already installed; nothing to do"
            return 0
            ;;
        esac
        note "found $installed; this will replace it with $VERSION"
    fi

    show_plan
    [ "$DRY_RUN" = 0 ] || {
        note "dry run: nothing was downloaded or installed"
        return 0
    }
    ask "Go ahead?" || {
        note "okay, nothing was changed"
        return 0
    }

    work=$(mktemp -d "${TMPDIR:-/tmp}/emrac-install.XXXXXX")
    trap 'rm -rf "$work"' EXIT INT TERM HUP
    cd "$work"

    note "downloading $TAG"
    curl -fsSL --proto '=https' --proto-redir '=https' --tlsv1.2 \
        -o "emrac-$TAG.tar.gz" "$URL" || die "the download failed"
    got=$(sha256sum "emrac-$TAG.tar.gz" | cut -d ' ' -f 1)
    if [ "$got" != "$SHA256" ]; then
        die "the downloaded file does not match the pinned checksum, so nothing was built.
  expected $SHA256
  got      $got
This can mean the download was tampered with, or that GitHub changed how it packs release tarballs. Do not continue; report it at https://github.com/pardhuvarmax/emrac/issues"
    fi
    note "checksum matches"

    write_pkgbuild
    note "building and installing (this takes a minute or two)"
    flags="-s -i -f --nocheck"
    [ "$ASSUME_YES" = 0 ] || flags="$flags --noconfirm"
    # The system toolchain first: another cargo earlier on PATH (a nix profile,
    # for instance) may not run on this system.
    # shellcheck disable=SC2086
    PATH="/usr/bin:$PATH" makepkg $flags || die "the build or the installation failed; see the output above"

    if command -v emrac >/dev/null 2>&1; then
        say ""
        emrac --version
        say ""
        note "done. Try: emrac doctor     Remove with: sudo pacman -Rns emrac"
    else
        note "installed, but 'emrac' is not on your PATH yet; open a new shell or run /usr/bin/emrac"
    fi
}

uninstall_emrac() {
    pacman -Q emrac >/dev/null 2>&1 || {
        note "emrac is not installed as a package; nothing to remove"
        return 0
    }
    say "This runs: sudo pacman -Rns emrac"
    say "(your own files under ~/.config/emrac, ~/.local/share/emrac and ~/.cache/emrac are not touched)"
    [ "$DRY_RUN" = 0 ] || {
        note "dry run: nothing was removed"
        return 0
    }
    ask "Remove emrac?" || {
        note "okay, nothing was changed"
        return 0
    }
    flags=""
    [ "$ASSUME_YES" = 0 ] || flags="--noconfirm"
    # shellcheck disable=SC2086
    sudo pacman -Rns $flags emrac
}

main() {
    for arg in "$@"; do
        case $arg in
        -y | --yes) ASSUME_YES=1 ;;
        -n | --dry-run) DRY_RUN=1 ;;
        --uninstall) UNINSTALL=1 ;;
        -h | --help)
            usage
            exit 0
            ;;
        *)
            usage >&2
            die "unknown option: $arg"
            ;;
        esac
    done

    check_system
    if [ "$UNINSTALL" = 1 ]; then
        uninstall_emrac
    else
        install_emrac
    fi
}

# Everything is defined before anything runs, so a download cut off halfway
# cannot execute part of the script.
main "$@"
