//! `emrac strays` (u25): files under `/usr` and `/opt` that no package owns, and
//! what each looks like it came from. Read only: nothing is changed or removed.

use emrac_core::strays::{self, Owned, Scan};
use emrac_core::{say, Result, Voice};

use crate::output::human_size as human;

pub struct Args<'a> {
    pub local: bool,
    pub generated: bool,
    pub path: Option<&'a str>,
    pub json: bool,
}

pub fn run(args: &Args) -> Result<()> {
    let owned: Owned = strays::read_owned(std::path::Path::new("/var/lib/pacman/local"));
    if owned.paths.is_empty() {
        say!(
            Voice::Warns,
            "pacman's file lists (/var/lib/pacman/local) could not be read, so nothing can be said about ownership."
        );
        return Ok(());
    }
    let base = strays::system_base();
    let custom = args.path.map(|p| p.trim_matches('/').to_string());
    let roots: Vec<&str> = match &custom {
        Some(p) if !p.is_empty() => vec![p.as_str()],
        _ => vec!["usr", "opt"],
    };
    let found = strays::scan(&Scan {
        base: &base,
        roots: &roots,
        owned: &owned,
        include_local: args.local,
        include_generated: args.generated,
    });
    if args.json {
        println!(
            "{}",
            serde_json::to_string_pretty(&found).unwrap_or_default()
        );
        return Ok(());
    }
    if found.is_empty() {
        say!(
            Voice::Confirms,
            "everything under {} belongs to a package{}.",
            roots
                .iter()
                .map(|r| format!("/{r}"))
                .collect::<Vec<_>>()
                .join(" and "),
            if args.generated {
                ""
            } else {
                " (or is generated by one)"
            }
        );
        return Ok(());
    }
    for (clue, items) in strays::group(&found) {
        let total: u64 = items.iter().map(|s| s.bytes).sum();
        println!(
            "\n{} \u{2014} {} ({})",
            clue.heading(),
            items.len(),
            human(total)
        );
        for s in items {
            println!(
                "  {}{}  {}  {}{}",
                s.path,
                if s.is_dir { "/" } else { "" },
                if s.is_dir {
                    format!("{} file{}", s.files, if s.files == 1 { "" } else { "s" })
                } else {
                    "file".to_string()
                },
                human(s.bytes),
                if s.mtime > 0 {
                    format!("  {}", emrac_core::format_utc_date(s.mtime))
                } else {
                    String::new()
                }
            );
        }
    }
    println!();
    say!(
        Voice::Found,
        "{} thing{} no package owns. Nothing was changed. `pacman -Qo <path>` confirms that nothing owns one; to put it under pacman's care, package it; to get rid of it, remove it yourself.",
        found.len(),
        if found.len() == 1 { "" } else { "s" }
    );
    Ok(())
}
