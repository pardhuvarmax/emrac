    #[test]
    fn a_download_is_accepted_only_if_it_matches_the_index() {
        let d = std::env::temp_dir().join(format!("emrac-selfdl-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(&d).unwrap();
        let src = d.join("src.tar.gz");
        fs::write(&src, b"hello").unwrap();
        let sha: String = Sha256::digest(b"hello")
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        let url = format!("file://{}", src.display());
        let dest = d.join("out.tar.gz");
        download_verified(&url, &dest, &sha).unwrap();
        assert_eq!(fs::read(&dest).unwrap(), b"hello");
        let bad = d.join("bad.tar.gz");
        let e = download_verified(&url, &bad, SHA).unwrap_err().to_string();
        assert!(e.contains("does not match the index"), "{e}");
        assert!(
            !bad.exists() && !bad.with_extension("part").exists(),
            "nothing is left behind"
        );
        assert!(download_verified("http://example.org/x", &bad, &sha).is_err());
        let _ = fs::remove_dir_all(&d);
    }

