//! `emrac self upgrade` and `emrac self downgrade` (u14, u15): the planning
//! (pure, tested) and the execution (download, verify, build with `makepkg`,
//! install with `sudo pacman -U`, check). pacman stays the authority for the
//! files: emrac never overwrites a file a package owns. See
//! `docs/plan/r2/u12-self-service.md`.

use std::fs;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use serde::Serialize;
use sha2::{Digest, Sha256};

use crate::config::SelfConfig;
use crate::error::{Error, Result};
use crate::self_check::{Owner, BUILD_SPACE};
use crate::self_meta::{self, Index, Release};
use crate::self_ops;

/// The recipe `install.sh` and the AUR package use; a test keeps them equal.
pub const RECIPE: &str = include_str!("../data/PKGBUILD.in");
const MAX_TARBALL: u64 = 200 * 1024 * 1024;

pub fn render_recipe(r: &Release) -> String {
    RECIPE
        .replace(
            "# Generated by emrac's install.sh",
            "# Generated by emrac self",
        )
        .replace("@VERSION@", &r.version)
        .replace("@TAG@", &r.tag)
        .replace("@SHA256@", &r.sha256)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Op {
    Upgrade,
    Downgrade,
}

impl Op {
    pub fn word(self) -> &'static str {
        match self {
            Op::Upgrade => "upgrade",
            Op::Downgrade => "downgrade",
        }
    }
}

/// Everything planning needs, gathered once (`gather_context`).
#[derive(Debug, Clone)]
pub struct Context {
    pub installed: String,
    pub owner: Owner,
    pub cfg: SelfConfig,
    pub index: Option<Index>,
    pub last_ok: Option<u64>,
    /// How the stored index was authenticated (`sync.json`).
    pub signature: String,
    /// `(program, package)` an upgrade needs and the machine lacks.
    pub tools_missing: Vec<(String, String)>,
    pub build_free: Option<u64>,
    /// Another self operation holds the lock.
    pub other_running: bool,
    /// The version of the files on disk (the highest schema emrac wrote).
    pub state_schema: u32,
    pub now: u64,
}

#[derive(Debug, Clone, Serialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum Outcome {
    /// Nothing to do, and why.
    Nothing { reason: String },
    /// Cannot be done, and every reason.
    Refused { reasons: Vec<String> },
    /// Can be done: the steps, and what to know first.
    Ready {
        target: Box<Release>,
        steps: Vec<String>,
        warnings: Vec<String>,
    },
}

#[derive(Debug, Clone, Serialize)]
pub struct Plan {
    pub op: Op,
    pub installed: String,
    pub outcome: Outcome,
}

/// Reasons the change cannot be made at all, whatever the target.
fn common_refusals(ctx: &Context) -> Vec<String> {
    let mut why = Vec::new();
    match &ctx.owner {
        Owner::Package { name, .. } if name == "emrac" => {}
        Owner::Package { name, .. } => why.push(format!(
            "the running binary belongs to the package '{name}', not 'emrac'; emrac does not change files another package owns"
        )),
        Owner::Cargo => why.push(
            "this copy was installed with `cargo install`; update it the same way (`cargo install --git https://github.com/pardhuvarmax/emrac --tag <tag>`), or install the package with install.sh".into(),
        ),
        Owner::Manual(p) => why.push(format!(
            "this copy ({p}) was put there by hand; replace it by hand, or install the package with install.sh so pacman owns it"
        )),
        Owner::Development => why.push(
            "this is a development build run from a cargo target folder; rebuild it from the source".into(),
        ),
        Owner::Unknown(w) => why.push(format!(
            "emrac can't tell how this copy was installed ({w}); it will not guess which tool owns it"
        )),
    }
    if ctx.cfg.require_signature && !ctx.signature.starts_with("signed by") {
        why.push("a signature is required, and the stored release index has no verified one: run `emrac self sync`".into());
    }
    for (name, package) in &ctx.tools_missing {
        why.push(format!(
            "{name} is missing (package {package}): `sudo pacman -S --needed {package}`"
        ));
    }
    if let Some(free) = ctx.build_free {
        if free < BUILD_SPACE {
            why.push(format!(
                "only {} MiB are free where the build runs; about {} MiB are needed",
                free / 1_048_576,
                BUILD_SPACE / 1_048_576
            ));
        }
    }
    if ctx.other_running {
        why.push("another emrac is upgrading or downgrading itself right now".into());
    }
    why
}

fn steps(op: Op, ctx: &Context, r: &Release) -> Vec<String> {
    vec![
        format!(
            "take the lock and write the journal (an interrupted {} is found next time)",
            op.word()
        ),
        "copy your configuration and emrac's data to a backup folder".to_string(),
        format!(
            "download {} and check its SHA-256 against the index ({})",
            r.tarball,
            &r.sha256[..16]
        ),
        format!(
            "unpack it: the top folder must be emrac-{} and its Cargo.toml must say {}",
            r.tag, r.version
        ),
        "build the package with makepkg from the recipe that install.sh and the AUR package use"
            .to_string(),
        format!(
            "install it with `sudo pacman -U` (pacman replaces /usr/bin/emrac; installed now: {})",
            match &ctx.owner {
                Owner::Package { version, .. } => version.clone(),
                _ => ctx.installed.clone(),
            }
        ),
        format!(
            "check that `emrac --version` says {} and that `emrac self check` still passes",
            r.version
        ),
        "remove the journal and write one line to the self log".to_string(),
    ]
}

fn stale_warning(ctx: &Context) -> Option<String> {
    let (age, stale) = self_meta::age_label(ctx.last_ok, ctx.now);
    stale.then(|| format!("the release index is {age}; the real run fetches a fresh one first"))
}

/// What `self upgrade` would do.
pub fn plan_upgrade(ctx: &Context) -> Plan {
    let outcome = (|| {
        let Some(index) = &ctx.index else {
            return Outcome::Refused {
                reasons: vec![
                    "emrac has no release information: run `emrac self sync` first".into(),
                ],
            };
        };
        let Some(target) = self_meta::newer_than(index, &ctx.cfg.channel, &ctx.installed) else {
            let latest = self_meta::latest(index, &ctx.cfg.channel)
                .map(|r| format!("{} ({})", r.tag, r.version))
                .unwrap_or_else(|| "none".into());
            return Outcome::Nothing {
                reason: format!(
                    "emrac {} is the newest release the {} channel offers (newest known: {latest}); nothing to do",
                    ctx.installed, ctx.cfg.channel
                ),
            };
        };
        let reasons = common_refusals(ctx);
        if !reasons.is_empty() {
            return Outcome::Refused { reasons };
        }
        let mut warnings: Vec<String> = stale_warning(ctx).into_iter().collect();
        if target.state_schema > ctx.state_schema {
            warnings.push(format!(
                "{} keeps its files in format {}, yours are {}: it will convert them the first time it runs, and the backup keeps the old ones",
                target.tag, target.state_schema, ctx.state_schema
            ));
        }
        Outcome::Ready {
            target: Box::new(target.clone()),
            steps: steps(Op::Upgrade, ctx, target),
            warnings,
        }
    })();
    Plan {
        op: Op::Upgrade,
        installed: ctx.installed.clone(),
        outcome,
    }
}

/// What `self downgrade` would do. `version` / `tag` name the target; with
/// neither, the single older release if there is exactly one.
pub fn plan_downgrade(ctx: &Context, version: Option<&str>, tag: Option<&str>) -> Plan {
    let outcome = (|| {
        let Some(index) = &ctx.index else {
            return Outcome::Refused {
                reasons: vec![
                    "emrac has no release information: run `emrac self sync` first".into(),
                ],
            };
        };
        let older = self_meta::older_than(index, &ctx.cfg.channel, &ctx.installed);
        let target: &Release = match (version, tag) {
            (Some(_), Some(_)) => {
                return Outcome::Refused {
                    reasons: vec!["give --version or --tag, not both".into()],
                }
            }
            (Some(v), None) => match older.iter().find(|r| r.version == v) {
                Some(r) => r,
                None => {
                    return if index.releases.iter().any(|r| r.version == v) {
                        Outcome::Refused {
                            reasons: vec![format!(
                                "{v} is not older than the installed {}, or the {} channel does not offer it",
                                ctx.installed, ctx.cfg.channel
                            )],
                        }
                    } else {
                        Outcome::Refused {
                            reasons: vec![format!(
                                "no release with version {v} is in the index (`emrac self news` lists releases)"
                            )],
                        }
                    }
                }
            },
            (None, Some(t)) => match older.iter().find(|r| r.tag == t) {
                Some(r) => r,
                None => {
                    return Outcome::Refused {
                        reasons: vec![format!(
                            "no older release with tag {t} is offered on the {} channel",
                            ctx.cfg.channel
                        )],
                    }
                }
            },
            (None, None) => match older.as_slice() {
                [] => {
                    return Outcome::Nothing {
                        reason: format!(
                            "no release older than {} is in the index; nothing to go back to",
                            ctx.installed
                        ),
                    }
                }
                [only] => only,
                many => {
                    return Outcome::Refused {
                        reasons: vec![format!(
                            "more than one older release is available: {}. Pick one with --version x.y.z or --tag <tag>",
                            many.iter()
                                .map(|r| format!("{} ({})", r.tag, r.version))
                                .collect::<Vec<_>>()
                                .join(", ")
                        )],
                    }
                }
            },
        };
        let mut reasons = common_refusals(ctx);
        if target.state_schema < ctx.state_schema {
            reasons.push(format!(
                "{} understands emrac's files in format {}, yours are in format {}: it could not read them. Nothing is converted backwards or deleted; use a release with format {} or newer",
                target.tag, target.state_schema, ctx.state_schema, ctx.state_schema
            ));
        }
        if !reasons.is_empty() {
            return Outcome::Refused { reasons };
        }
        let mut warnings: Vec<String> = stale_warning(ctx).into_iter().collect();
        warnings.push(format!(
            "settings or data your current version added since {} may be ignored or refused by it; your files are not changed, and the backup keeps them exactly as they are now",
            target.tag
        ));
        let same: Vec<&str> = older
            .iter()
            .filter(|r| r.version == target.version && r.tag != target.tag)
            .map(|r| r.tag.as_str())
            .collect();
        if !same.is_empty() {
            warnings.push(format!(
                "{} also have version {}; this plan uses {}, the newest of them",
                same.join(", "),
                target.version,
                target.tag
            ));
        }
        Outcome::Ready {
            target: Box::new(target.clone()),
            steps: steps(Op::Downgrade, ctx, target),
            warnings,
        }
    })();
    Plan {
        op: Op::Downgrade,
        installed: ctx.installed.clone(),
        outcome,
    }
}

// ------------------------------------------------------------ the files

fn err(msg: impl Into<String>) -> Error {
    Error::SelfService(msg.into())
}

fn io(path: &Path, e: std::io::Error) -> Error {
    err(format!("{}: {e}", path.display()))
}

/// Copies the user's configuration and emrac's data (not the self folder) to
/// `<self dir>/backup-<now>/`. Returns that folder.
pub fn backup_state(now: u64) -> Result<PathBuf> {
    let home = std::env::var("HOME").map_err(|_| Error::NoDataDir)?;
    let dest = self_meta::dir()?.join(format!("backup-{now}"));
    backup_state_at(Path::new(&home), &dest)?;
    Ok(dest)
}

fn backup_state_at(home: &Path, dest: &Path) -> Result<()> {
    fs::create_dir_all(dest).map_err(|e| io(dest, e))?;
    copy_tree(&home.join(".config/emrac"), &dest.join("config"), &[])?;
    copy_tree(
        &home.join(".local/share/emrac"),
        &dest.join("data"),
        &["self"],
    )?;
    Ok(())
}

fn copy_tree(from: &Path, to: &Path, skip: &[&str]) -> Result<()> {
    let Ok(rd) = fs::read_dir(from) else {
        return Ok(());
    };
    fs::create_dir_all(to).map_err(|e| io(to, e))?;
    for entry in rd.flatten() {
        let name = entry.file_name();
        if skip.iter().any(|s| name == *s) {
            continue;
        }
        let (src, dst) = (entry.path(), to.join(&name));
        let ft = entry.file_type().map_err(|e| io(&src, e))?;
        if ft.is_dir() {
            copy_tree(&src, &dst, &[])?;
        } else if ft.is_file() {
            fs::copy(&src, &dst).map_err(|e| io(&src, e))?;
        }
    }
    Ok(())
}

/// Removes a staging folder even when a build left folders in it that its
/// owner cannot enter (makepkg's `pkg/` under fakeroot, a test's fixture): the
/// permissions are widened first, since a plain removal stops at the first one.
pub fn remove_tree(dir: &Path) {
    use std::os::unix::fs::PermissionsExt;
    fn relax(p: &Path) {
        let Ok(meta) = fs::symlink_metadata(p) else {
            return;
        };
        if meta.is_dir() {
            let _ = fs::set_permissions(p, fs::Permissions::from_mode(0o700));
            if let Ok(rd) = fs::read_dir(p) {
                for e in rd.flatten() {
                    relax(&e.path());
                }
            }
        }
    }
    relax(dir);
    let _ = fs::remove_dir_all(dir);
}

/// Downloads `url` to `dest`, checking the SHA-256 as it goes. `https://` or,
/// for a local mirror, `file://`.
pub fn download_verified(url: &str, dest: &Path, sha256: &str) -> Result<()> {
    let part = dest.with_extension("part");
    let result = (|| {
        let mut out = fs::File::create(&part).map_err(|e| io(&part, e))?;
        let mut hasher = Sha256::new();
        let mut total = 0u64;
        let mut reader: Box<dyn Read> = if let Some(path) = url.strip_prefix("file://") {
            Box::new(fs::File::open(path).map_err(|e| err(format!("{path}: {e}")))?)
        } else if url.starts_with("https://") {
            let resp = ureq::get(url)
                .header("User-Agent", concat!("emrac/", env!("CARGO_PKG_VERSION")))
                .config()
                .timeout_global(Some(std::time::Duration::from_secs(600)))
                .build()
                .call()
                .map_err(|e| err(format!("couldn't download {url}: {e}")))?;
            Box::new(resp.into_body().into_reader())
        } else {
            return Err(err(format!(
                "'{url}' is not an https:// or file:// address"
            )));
        };
        let mut buf = [0u8; 64 * 1024];
        loop {
            let n = reader
                .read(&mut buf)
                .map_err(|e| err(format!("download interrupted: {e}")))?;
            if n == 0 {
                break;
            }
            total += n as u64;
            if total > MAX_TARBALL {
                return Err(err(format!(
                    "{url} is over {} MiB: refused",
                    MAX_TARBALL / 1_048_576
                )));
            }
            hasher.update(&buf[..n]);
            out.write_all(&buf[..n]).map_err(|e| io(&part, e))?;
        }
        out.sync_all().map_err(|e| io(&part, e))?;
        let got: String = hasher
            .finalize()
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        if got != sha256 {
            return Err(err(format!(
                "the download does not match the index: expected SHA-256 {sha256}, got {got}; nothing was built"
            )));
        }
        fs::rename(&part, dest).map_err(|e| io(dest, e))
    })();
    if result.is_err() {
        let _ = fs::remove_file(&part);
    }
    result
}

/// The first path in a tarball, and the text of one member.
pub fn tar_top_and_member(tarball: &Path, member_in_top: &str) -> Result<(String, String)> {
    let list = Command::new("tar")
        .arg("tzf")
        .arg(tarball)
        .output()
        .map_err(|e| err(format!("couldn't run tar: {e}")))?;
    if !list.status.success() {
        return Err(err("tar could not read the downloaded file as a tarball"));
    }
    let first = String::from_utf8_lossy(&list.stdout)
        .lines()
        .next()
        .unwrap_or("")
        .to_string();
    let top = first.split('/').next().unwrap_or("").to_string();
    if top.is_empty() || top.contains("..") {
        return Err(err("the tarball has no usable top folder"));
    }
    let member = Command::new("tar")
        .arg("xzf")
        .arg(tarball)
        .arg("--to-stdout")
        .arg(format!("{top}/{member_in_top}"))
        .output()
        .map_err(|e| err(format!("couldn't run tar: {e}")))?;
    Ok((top, String::from_utf8_lossy(&member.stdout).into_owned()))
}

/// The `version = "x.y.z"` line of a Cargo.toml.
pub fn cargo_version(cargo_toml: &str) -> Option<String> {
    cargo_toml
        .lines()
        .find_map(|l| l.strip_prefix("version = \"")?.strip_suffix('"'))
        .map(str::to_string)
}

// ------------------------------------------------------------- execution

#[derive(Debug, Clone)]
pub struct ExecOptions {
    /// `--yes`: pacman is told `--noconfirm`.
    pub yes: bool,
    /// Skip the package's test run.
    pub skip_tests: bool,
}

#[derive(Debug, Clone, Serialize)]
pub struct Report {
    pub op: Op,
    pub from: String,
    pub to: String,
    pub tag: String,
    pub backup: String,
    /// The new binary reports the target version.
    pub version_ok: bool,
    /// `self check` of the new binary exited with 0 (or 1 with no new problem).
    pub check_ok: bool,
    pub notes: Vec<String>,
}

fn run(cmd: &mut Command, what: &str) -> Result<()> {
    let status = cmd
        .status()
        .map_err(|e| err(format!("couldn't run {what}: {e}")))?;
    if status.success() {
        Ok(())
    } else {
        Err(err(format!("{what} failed ({status})")))
    }
}

/// Makes the change described by `release`. `say` reports each phase.
pub fn execute(
    op: Op,
    release: &Release,
    installed: &str,
    opts: &ExecOptions,
    say: &mut dyn FnMut(&str),
) -> Result<Report> {
    let now = crate::journal::unix_now();
    let mut guard = self_ops::begin(op.word(), installed, &release.version, &release.tag, now)?;
    let home = std::env::var("HOME").map_err(|_| Error::NoDataDir)?;
    let stage = Path::new(&home)
        .join(".cache/emrac/self")
        .join(format!("{}-{now}", release.tag));

    let outcome = (|| -> Result<Report> {
        say("copying your configuration and data to a backup folder");
        let backup = backup_state(now)?;
        guard.backup(&backup)?;

        guard.phase("stage")?;
        let build = stage.join("build");
        fs::create_dir_all(&build).map_err(|e| io(&build, e))?;
        let tarball = build.join(format!("emrac-{}.tar.gz", release.tag));
        say(&format!("downloading {}", release.tarball));
        download_verified(&release.tarball, &tarball, &release.sha256)?;
        say("the download matches the index; checking what is inside");
        let (top, cargo) = tar_top_and_member(&tarball, "Cargo.toml")?;
        if top != format!("emrac-{}", release.tag) {
            return Err(err(format!(
                "the tarball unpacks to '{top}', expected 'emrac-{}': refused",
                release.tag
            )));
        }
        match cargo_version(&cargo) {
            Some(v) if v == release.version => {}
            other => {
                return Err(err(format!(
                    "the index promises version {}, the tarball's Cargo.toml says {}: refused",
                    release.version,
                    other.unwrap_or_else(|| "nothing readable".into())
                )))
            }
        }
        fs::write(build.join("PKGBUILD"), render_recipe(release)).map_err(|e| io(&build, e))?;

        guard.phase("activate")?;
        say("building the package with makepkg (this compiles emrac; it takes a few minutes)");
        let mut makepkg = Command::new("makepkg");
        makepkg
            .args(["-f", "--noconfirm"])
            .current_dir(&build)
            .env("PKGDEST", &build)
            .env("SRCDEST", &build)
            .env(
                "PATH",
                format!("/usr/bin:{}", std::env::var("PATH").unwrap_or_default()),
            );
        if opts.skip_tests {
            makepkg.arg("--nocheck");
        }
        run(&mut makepkg, "makepkg")?;
        let package = fs::read_dir(&build)
            .map_err(|e| io(&build, e))?
            .flatten()
            .map(|e| e.path())
            .find(|p| {
                p.file_name().and_then(|n| n.to_str()).is_some_and(|n| {
                    n.starts_with(&format!("emrac-{}-", release.version)) && n.contains(".pkg.tar")
                })
            })
            .ok_or_else(|| err("makepkg finished but left no package file"))?;
        say(&format!("installing {} with pacman", package.display()));
        let mut pacman = Command::new("sudo");
        pacman.arg("pacman").arg("-U");
        if opts.yes {
            pacman.arg("--noconfirm");
        }
        pacman.arg(&package);
        run(&mut pacman, "sudo pacman -U")?;

        guard.phase("verify")?;
        let mut notes = Vec::new();
        let new = Command::new("/usr/bin/emrac").arg("--version").output();
        let version_ok = new
            .as_ref()
            .map(|o| String::from_utf8_lossy(&o.stdout).contains(&release.version))
            .unwrap_or(false);
        if !version_ok {
            notes.push(format!(
                "the installed /usr/bin/emrac does not report {}",
                release.version
            ));
        }
        let check = Command::new("/usr/bin/emrac")
            .args(["self", "check", "--json"])
            .stderr(Stdio::null())
            .output();
        let check_ok = check.as_ref().map(|o| o.status.success()).unwrap_or(false);
        if !check_ok {
            notes.push("`emrac self check` on the new version reports a problem".into());
        }
        Ok(Report {
            op,
            from: installed.to_string(),
            to: release.version.clone(),
            tag: release.tag.clone(),
            backup: backup.display().to_string(),
            version_ok,
            check_ok,
            notes,
        })
    })();

    remove_tree(&stage);
    append_log(
        now,
        op,
        installed,
        release,
        match &outcome {
            Ok(r) if r.version_ok && r.check_ok => "ok",
            Ok(_) => "installed, check failed",
            Err(_) => "failed",
        },
    );
    guard.finish();
    outcome
}

/// One JSON line per operation, in `~/.local/share/emrac/self/log.jsonl`.
fn append_log(now: u64, op: Op, from: &str, r: &Release, result: &str) {
    let Ok(dir) = self_meta::dir() else { return };
    let line = serde_json::json!({
        "time": now, "op": op.word(), "from": from, "to": r.version, "tag": r.tag, "result": result,
    });
    if let Ok(mut f) = fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(dir.join("log.jsonl"))
    {
        let _ = writeln!(f, "{line}");
    }
}

// --------------------------------------------------------------- gathering

pub fn gather_context() -> Context {
    let cfg = crate::Config::load()
        .map(|c| c.self_service)
        .unwrap_or_default();
    let facts = crate::self_check::gather();
    let deep = crate::self_check::gather_deep(false);
    let stored = self_meta::load().ok();
    let tools_missing = deep
        .needs
        .iter()
        .filter(|n| !n.present)
        .map(|n| (n.name.to_string(), n.package.to_string()))
        .collect();
    Context {
        installed: env!("CARGO_PKG_VERSION").to_string(),
        owner: facts.owner,
        cfg,
        last_ok: stored
            .as_ref()
            .and_then(|s| s.state.as_ref())
            .and_then(|s| s.last_ok),
        signature: stored
            .as_ref()
            .and_then(|s| s.state.as_ref())
            .map(|s| s.signature.clone())
            .unwrap_or_default(),
        index: stored.and_then(|s| s.index),
        tools_missing,
        build_free: deep.build_free,
        other_running: matches!(self_ops::state(), Ok(self_ops::State::Running)),
        state_schema: self_meta::STATE_SCHEMA,
        now: crate::journal::unix_now(),
    }
}

